#!/bin/sh
# Writes config.js from environment variables, for the browser to read.
#
#   export LEAD_DESK_WEBHOOK_URL="https://..."
#   sh generate-config.sh
#
# On Netlify / Vercel: set LEAD_DESK_WEBHOOK_URL in the site's environment
# settings and use "sh generate-config.sh" as the build command.
#
# Note: whatever goes into config.js is visible to anyone who opens the site.
# This keeps the URL out of your source code, not secret from visitors.

set -e
cd "$(dirname "$0")"

if [ -z "$LEAD_DESK_WEBHOOK_URL" ]; then
  echo "Warning: LEAD_DESK_WEBHOOK_URL is not set; the enquiry form will show 'not connected'." >&2
fi

# Escape backslashes and double quotes for a JS string
url=$(printf '%s' "$LEAD_DESK_WEBHOOK_URL" | sed 's/\\/\\\\/g; s/"/\\"/g')

cat > config.js <<EOF
// Generated by generate-config.sh. Do not edit by hand.
window.SITE_CONFIG = {
  LEAD_DESK_WEBHOOK_URL: "$url"
};
EOF

echo "config.js written."
